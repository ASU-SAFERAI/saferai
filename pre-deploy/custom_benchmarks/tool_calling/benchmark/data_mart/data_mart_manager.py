"""Redshift connection + append-only insert (ported from the pre-release container).

``DatabaseManager`` opens a psycopg2 connection to the Redshift data mart (TLS
required). ``InsertManager`` performs append-only inserts into the identity-PK
``SUPER`` payload tables, running ``CREATE TABLE IF NOT EXISTS`` once per process
and wrapping payload columns in ``JSON_PARSE`` so a JSON string lands as a native
``SUPER`` value. A failed batch is rolled back and re-raised.

``psycopg2`` is imported lazily so this module (and the rest of the benchmark)
imports cleanly in environments where the Redshift driver is not installed; the
dependency is only required when a connection is actually opened.
"""
from __future__ import annotations

from typing import Any, List, Sequence, Tuple

from .._common import logger
from .config import DataMartCredentials
from .data_mart_table import TableConfiguration

# Database constants (match the pre-release container).
SSLMODE = "require"


def _require_psycopg2():
    """Import psycopg2 on demand with an actionable error if it is missing."""
    try:
        import psycopg2  # noqa: WPS433 - intentional lazy import
    except ImportError as exc:  # pragma: no cover - exercised via dependency tests
        raise ImportError(
            "Writing to the Redshift data mart requires psycopg2. Install it "
            "with 'pip install psycopg2-binary' (the data-mart write is optional "
            "and off by default)."
        ) from exc
    return psycopg2


class DatabaseManager:
    """Handles Redshift connections and query execution."""

    def __init__(self, credentials: DataMartCredentials):
        self._credentials = credentials
        self.connection_params = {
            "host": credentials.host,
            "port": credentials.port,
            "user": credentials.username,
            "password": credentials.password,
            "dbname": credentials.database,
            "sslmode": SSLMODE,
        }

    def get_connection(self):
        """Create and return a Redshift connection."""
        psycopg2 = _require_psycopg2()
        return psycopg2.connect(**self.connection_params)

    def execute_query(
        self,
        query: str,
        params: Tuple | None = None,
        fetch: bool = False,
    ):
        """Execute a query with optional parameters."""
        with self.get_connection() as conn:
            try:
                with conn.cursor() as cur:
                    cur.execute(query, params)
                    if fetch:
                        return cur.fetchall()
                    conn.commit()
            finally:
                conn.close()


class InsertManager:
    """Manages append-only insert operations for identity-PK data-mart tables."""

    def __init__(self, db_manager: DatabaseManager):
        self.db_manager = db_manager
        self._tables_ensured: set[str] = set()

    def _ensure_table(self, table_name: str, config: dict) -> None:
        """Run the table's CREATE TABLE IF NOT EXISTS DDL once per process."""
        if table_name in self._tables_ensured:
            return
        with self.db_manager.get_connection() as conn:
            try:
                with conn.cursor() as cur:
                    cur.execute(config["create_main_ddl"])
                conn.commit()
            finally:
                conn.close()
        self._tables_ensured.add(table_name)

    def insert_records(self, records: Sequence[Tuple], table_name: str) -> None:
        """Append rows into the data-mart table.

        The identity PK (``id``) is generated by Redshift on each insert, and
        the timestamps default to ``CURRENT_TIMESTAMP``. Each record is a tuple
        of the data-column values in ``config['data_cols']`` order; ``SUPER``
        columns are JSON strings wrapped in ``JSON_PARSE`` by the insert SQL.
        """
        config = TableConfiguration.get_table_config(table_name)
        self._ensure_table(table_name, config)

        logger.info(
            "Inserting %d record(s) into %s", len(records), config["main_table"]
        )
        with self.db_manager.get_connection() as conn:
            try:
                with conn.cursor() as cur:
                    cur.executemany(self._build_insert_sql(config), list(records))
                conn.commit()
                logger.info(
                    "Insert completed for %s: %d row(s)",
                    config["main_table"], len(records),
                )
            except Exception as exc:
                conn.rollback()
                logger.error("Insert failed for %s: %s", config["main_table"], exc)
                raise
            finally:
                conn.close()

    @staticmethod
    def _build_insert_sql(config: dict) -> str:
        """Build the append-only INSERT, wrapping SUPER columns in JSON_PARSE."""
        columns = ", ".join(config["data_cols"])
        placeholders = ", ".join(
            "JSON_PARSE(%s)" if col in config["super_cols"] else "%s"
            for col in config["data_cols"]
        )
        return (
            f"INSERT INTO {config['main_table']} "
            f"({columns}, created_at_dttm, last_updated_at_dttm) "
            f"VALUES ({placeholders}, CURRENT_TIMESTAMP, CURRENT_TIMESTAMP);"
        )
